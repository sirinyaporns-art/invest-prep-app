export function calculateTSIRisk(answers: Record<number, number>): {
  totalScore: number;
  riskProfile: RiskProfile;
  answeredCount: number;
} {
  let totalScore = 0;
  let answeredCount = 0;

  for (const q of TSI_QUESTIONS) {
    const selectedOptionIdx = answers[q.id];
    if (selectedOptionIdx !== undefined && q.options[selectedOptionIdx]) {
      totalScore += q.options[selectedOptionIdx].score;
      answeredCount++;
    }
  }

  let level: RiskLevel = 1;
  if (totalScore < 15) level = 1;
  else if (totalScore <= 21) level = 2;
  else if (totalScore <= 29) level = 3;
  else if (totalScore <= 36) level = 4;
  else level = 5;

  return {
    totalScore,
    riskProfile: RISK_PROFILES[level],
    answeredCount,
  };
}
